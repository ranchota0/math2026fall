from __future__ import annotations


def pair(text: str) -> tuple[str, str]:
    in_math = False
    for index, character in enumerate(text):
        if character == "$":
            in_math = not in_math
        elif character == "|" and not in_math:
            return text[:index], text[index + 1 :]
    raise ValueError(f"missing question/answer separator: {text}")


def card(
    hook: str,
    core: str,
    examples: list[str],
    drills: list[str],
    error: str,
    application: str,
    *,
    method: str,
    figure: str | None = None,
) -> dict:
    return {
        "hook": pair(hook),
        "core": pair(core),
        "examples": [pair(item) for item in examples],
        "drills": [pair(item) for item in drills],
        "error": pair(error),
        "application": pair(application),
        "method": method,
        "figure": figure,
    }


